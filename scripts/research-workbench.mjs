import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTypeScript } from './load-typescript.mjs';
import { withResearchLock, commitFiles, assertHealthy, digest, transactions, recoverTransaction, reclaimDeadLock, backupResearch, extractBackup } from './research-storage.mjs';
import { dataVersion, versionFile, checkVersionFile } from './research-version.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ledger = loadTypeScript(path.join(projectRoot, 'src/lib/researchLedger.ts'));
const { applyResearchPatches } = loadTypeScript(path.join(projectRoot, 'src/lib/researchProjection.ts'));
const { previewPublicChanges } = loadTypeScript(path.join(projectRoot, 'src/lib/researchPreview.ts'));
const { SCHOOL_IDENTITIES: schools } = loadTypeScript(path.join(projectRoot, 'src/data/schoolIdentities.ts'));
const { OFFICIALS_DATA: baseline, UNITS_DATA: units } = loadTypeScript(path.join(projectRoot, 'src/data/legacyData.ts'));
const dataDirectory = root => path.join(root, 'research-data/people');
const outputFile = root => path.join(root, 'src/data/generatedResearch.ts');

function parseDossier(text) {
  const value = JSON.parse(text);
  if (!value || typeof value !== 'object' || !['evidence', 'facts', 'rules', 'publications'].every(key => Array.isArray(value[key]))) throw Error('不是有效的研究人物文件');
  return value;
}
export function loadResearchStore(root = projectRoot) {
  assertHealthy(root);
  const dir = dataDirectory(root);
  if (!fs.existsSync(dir)) throw Error('研究库目录缺失，拒绝用空库覆盖公开投影');
  if (fs.lstatSync(dir).isSymbolicLink()) throw Error('研究目录不得为符号链接');
  return fs.readdirSync(dir).filter(file => file.endsWith('.json')).sort().map(file => {
    const filename = path.join(dir, file);
    if (fs.lstatSync(filename).isSymbolicLink()) throw Error('研究人物文件不得为符号链接');
    const dossier = parseDossier(fs.readFileSync(filename, 'utf8'));
    if (file !== `${dossier.personId}.json`) throw Error(`文件名与人物ID不一致：${file}`);
    return dossier;
  });
}
export function validateStore(store) {
  const errors = ledger.validateResearchStore(store);
  for (const dossier of store) if (!baseline.some(p => p.id === dossier.personId)) errors.push(`未注册的人物：${dossier.personId}`);
  if (errors.length) throw Error(errors.join('\n'));
  const patches = ledger.compileResearchPatches(store);
  for (const patch of patches) if (patch.target.field === 'unitId' && patch.value && !units.some(u => u.id === patch.value)) throw Error(`机构ID不存在：${patch.value}`);
  return patches;
}
export function projectionText(store) {
  const patches = validateStore(store);
  return '// Generated by npm run research:export. Do not edit manually.\n'
    + "import type { PublicResearchPatch } from '../types/research';\n"
    + `export const PUBLIC_RESEARCH_PATCHES: PublicResearchPatch[] = ${JSON.stringify(patches, null, 2)};\n`;
}
function assertNoLostBindings(root, text) {
  const file = outputFile(root);
  if (!fs.existsSync(file)) return;
  const read = content => {
    const match = content.match(/PUBLIC_RESEARCH_PATCHES: PublicResearchPatch\[\] = ([\s\S]+);\s*$/);
    if (!match) throw Error('已有公开投影格式异常；拒绝覆盖，请检查文件');
    return JSON.parse(match[1]);
  };
  const next = new Set(read(text).map(p => `${p.personId}/${ledger.targetKey(p.target)}`));
  for (const patch of read(fs.readFileSync(file, 'utf8'))) {
    if (!next.has(`${patch.personId}/${ledger.targetKey(patch.target)}`)) throw Error('已接管字段从研究库消失；应追加 withdraw 事件，不能删除库文件或发布历史');
  }
}
export function exportResearch(root = projectRoot, check = false) {
  const run = () => {
    const text = projectionText(loadResearchStore(root));
    const file = outputFile(root);
    assertNoLostBindings(root, text);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) throw Error('公开投影已过期，请运行 npm run research:export，再构建／重启预览。');
      checkVersionFile(root);
    } else {
      const writes = { 'src/data/generatedResearch.ts': text };
      writes['src/data/generatedResearchVersion.ts'] = versionFile(dataVersion(root, writes));
      if (Object.entries(writes).some(([name, value]) => !fs.existsSync(path.join(root, name)) || fs.readFileSync(path.join(root, name), 'utf8') !== value)) commitFiles(root, writes, { kind: 'export' });
    }
    return text;
  };
  return check ? run() : withResearchLock(root, run);
}
export function importDossier(filename, root = projectRoot, write = false, expectedToken) {
  const run = () => {
    const previous = loadResearchStore(root);
    const draftText = fs.readFileSync(filename, 'utf8');
    const next = parseDossier(draftText);
    const baseVersion = dataVersion(root);
    const previewToken = digest(`${baseVersion}\n${draftText}`);
    if (write && expectedToken !== previewToken) throw Error('缺少有效预览确认码，或数据／草稿已变化；重新预览后使用 --write --expect <previewToken>');
    const old = previous.find(d => d.personId === next.personId);
    if (old) ledger.assertAppendOnly(old, next);
    const store = [...previous.filter(d => d.personId !== next.personId), next].sort((a, b) => a.personId.localeCompare(b.personId));
    validateStore(store);
    // 新发布动作必须满足门槛；既有发布项随新证据自动失效，无须删除历史发布事件。
    for (const event of next.publications.slice(old?.publications.length || 0)) {
      const fact = ledger.latest(next.facts, event.factId);
      if (event.action === 'publish' && ledger.evaluateFact(store, next.personId, fact).state !== 'eligible') throw Error(`不允许发布未核验／失效事实：${event.factId}`);
    }
    const text = projectionText(store); // 所有校验通过后才写文件
    assertNoLostBindings(root, text);
    const projected = applyResearchPatches(baseline, ledger.compileResearchPatches(store));
    const preview = previewPublicChanges(applyResearchPatches(baseline, ledger.compileResearchPatches(previous)), projected, previous, store, units, schools);
    const warnings = projected.flatMap(p => (p.researchNotices || []).map(note => `${p.id}: ${note}`));
    if (write) {
      if (dataVersion(root) !== baseVersion || fs.readFileSync(filename, 'utf8') !== draftText) throw Error('预览计算期间输入已变化，拒绝写入');
      const writes = { [`research-data/people/${next.personId}.json`]: JSON.stringify(next, null, 2) + '\n', 'src/data/generatedResearch.ts': text };
      writes['src/data/generatedResearchVersion.ts'] = versionFile(dataVersion(root, writes));
      commitFiles(root, writes);
    }
    return { personId: next.personId, written: write, previewToken, facts: ledger.currentFacts(next).length, preview, warnings };
  };
  return write ? withResearchLock(root, run) : run();
}
export function researchReport(store) {
  validateStore(store);
  return store.map(dossier => ({ personId: dossier.personId,
    facts: ledger.currentFacts(dossier).map(fact => ({ id: fact.id, revision: fact.revision, target: ledger.targetKey(fact.target),
      status: fact.status, ...ledger.evaluateFact(store, dossier.personId, fact),
      publication: [...dossier.publications].reverse().find(e => e.factId === fact.id)?.action || 'not_published' })),
    sourceGroups: new Set(dossier.evidence.map(e => e.originGroup)).size,
    evidenceRevisions: dossier.evidence.length,
  }));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const [command = 'report', filename, ...flags] = process.argv.slice(2);
    if (command === 'export' || command === 'check') { exportResearch(projectRoot, command === 'check'); console.log('研究公开投影：通过'); }
    else if (command === 'report' || command === 'validate') console.log(JSON.stringify(researchReport(loadResearchStore()), null, 2));
    else if (command === 'import' && filename && (!flags.length || (flags.length === 3 && flags[0] === '--write' && flags[1] === '--expect'))) console.log(JSON.stringify(importDossier(path.resolve(filename), projectRoot, flags[0] === '--write', flags[2]), null, 2));
    else if (command === 'recovery') console.log(JSON.stringify(transactions(projectRoot).map(({ id, kind, status, at }) => ({ id, kind, status, at })), null, 2));
    else if (command === 'recover' && filename && ['resume', 'rollback'].includes(flags[0]) && (!flags[1] || flags[1] === '--write')) console.log(JSON.stringify(recoverTransaction(projectRoot, filename, flags[0], flags[1] === '--write'), null, 2));
    else if (command === 'unlock') console.log(JSON.stringify(reclaimDeadLock(projectRoot), null, 2));
    else if (command === 'backup') { loadResearchStore(); console.log(JSON.stringify({ backupId: backupResearch(projectRoot) })); }
    else if (command === 'restore-backup' && filename && !flags.length) console.log(JSON.stringify(extractBackup(projectRoot, filename), null, 2));
    else throw Error('用法：report|export|check|import <人物JSON> [--write --expect <预览码>]|recovery|recover <事务ID> resume/rollback [--write]|unlock|backup');
  } catch (error) { console.error(`研究工作台：${error.message}`); process.exitCode = 1; }
}
