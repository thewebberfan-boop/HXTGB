import fs from 'node:fs';
import path from 'node:path';
import { digest, readOptional, assertHealthy } from './research-storage.mjs';

export function inputFiles(root) {
  const files = [];
  const scan = relative => {
    const dir = path.join(root, relative);
    if (!fs.existsSync(dir)) return;
    if (fs.lstatSync(dir).isSymbolicLink()) throw Error('版本输入不得使用符号链接');
    for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = `${relative}/${item.name}`;
      if (item.isSymbolicLink()) throw Error('版本输入不得使用符号链接');
      if (item.isDirectory()) scan(file);
      else if (/\.(ts|tsx|mjs|json|css)$/.test(file) && file !== 'src/data/generatedResearchVersion.ts') files.push(file);
    }
  };
  for (const dir of ['src', 'scripts', 'research-data/people']) scan(dir);
  for (const file of ['package.json', 'package-lock.json', 'tsconfig.json', 'next.config.js', 'next.config.mjs', 'next.config.ts']) if (fs.existsSync(path.join(root, file))) files.push(file);
  return files.sort();
}
export function dataVersion(root, overrides = {}) {
  const files = [...new Set([...inputFiles(root), ...Object.keys(overrides).filter(f => f !== 'src/data/generatedResearchVersion.ts')])].sort();
  return digest(JSON.stringify(files.map(file => [file, file in overrides ? overrides[file] : readOptional(path.join(root, file))])));
}
export function versionFile(version) {
  return `// Generated by the research workbench. Do not edit manually.\nexport const PUBLIC_DATA_VERSION = ${JSON.stringify(version)};\n`;
}
export function checkVersionFile(root) {
  assertHealthy(root);
  const version = dataVersion(root);
  if (readOptional(path.join(root, 'src/data/generatedResearchVersion.ts')) !== versionFile(version)) throw Error('数据或代码版本已变化，请先 research:export，再重新构建');
  return version;
}
export function checkRelease(root) {
  const version = checkVersionFile(root);
  const seal = JSON.parse(readOptional(path.join(root, '.next/research-release.json')) || '{}');
  const buildId = readOptional(path.join(root, '.next/BUILD_ID'))?.trim();
  if (!buildId || seal.version !== version || seal.buildId !== buildId || seal.status !== 'ready') throw Error('构建未完成或与当前数据不一致，拒绝启动；请运行 npm run build');
  return { version, buildId };
}
/** 只向网页返回版本和有限状态，不包含研究内容、文件路径或错误详情。 */
export function runtimeVersion(root, runningVersion) {
  try {
    assertHealthy(root);
  } catch { return { state: 'recovery_required', runningVersion }; }
  try {
    const currentVersion = dataVersion(root);
    const generatedMatches = readOptional(path.join(root, 'src/data/generatedResearchVersion.ts')) === versionFile(currentVersion);
    return { state: generatedMatches && runningVersion === currentVersion ? 'ok' : 'stale', runningVersion, currentVersion };
  } catch {
    return { state: 'unavailable', runningVersion };
  }
}
